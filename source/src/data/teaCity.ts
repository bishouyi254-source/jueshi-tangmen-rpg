/**
 * 根据目标性别获取人物的三版描述（外貌/性格/背景）。
 * - 如果人物已提供 alt* 字段（另一性别定制版），直接使用；
 * - 否则用通用性别词汇替换做程序化转换；
 * - 目标性别与原始性别一致时返回原版。
 */
export function getGenderedCharacter(c: TeaCityCharacter, targetGender: 'male' | 'female'): {
  appearance: string;
  personality: string;
  background: string;
} {
  const originalIsMale = c.gender === '男';
  const targetIsMale = targetGender === 'male';
  if (originalIsMale === targetIsMale) {
    return { appearance: c.appearance, personality: c.personality, background: c.background };
  }
  // 定制版优先
  if (c.altAppearance || c.altPersonality || c.altBackground) {
    return {
      appearance: c.altAppearance ?? genderedText(c.appearance, targetGender),
      personality: c.altPersonality ?? genderedText(c.personality, targetGender),
      background: c.altBackground ?? genderedText(c.background, targetGender),
    };
  }
  return {
    appearance: genderedText(c.appearance, targetGender),
    personality: genderedText(c.personality, targetGender),
    background: genderedText(c.background, targetGender),
  };
}

