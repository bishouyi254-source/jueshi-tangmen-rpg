// EXPORTS: TeaCityCharacter, TEA_CITY_CHARACTERS, TEA_CITY_NODES

/** 茶城人物定义 */
export interface TeaCityCharacter {
  id: string;
  name: string;
  title: string; // 称号/身份
  faction: string; // 势力/宗门归属（原著设定）
  gender: '男' | '女';
  martialSoul: string; // 武魂
  soulType: string; // 魂师类型
  quality: 'common' | 'rare' | 'fine' | 'epic' | 'legendary';
  realm: string; // 修为境界
  iconChar: string; // 头像图标字
  appearance: string; // 外貌描述（详细）
  personality: string; // 性格描述
  background: string; // 背景故事
  // 另一性别版本（结为情侣选择性别时使用；未提供时用通用转换）
  altAppearance?: string;
  altPersonality?: string;
  altBackground?: string;
  genderLocked?: boolean;  // 性别是否锁定（锁定则结为情侣时不弹性别选择，固定为 gender 字段）
  encounterChance: number; // 遇到概率 0-1
  favoriteGift?: string; // 喜欢的礼物类型描述
  levelRequired?: number; // 结识所需最低等级（不填则无限制）
  /** 特殊好感度机制：gift=赠送礼物（默认）/ challenge=挑战获胜 */
  favorMechanism?: 'gift' | 'challenge';
   challengeHp?: number;   // 挑战模式下的血量（第一阶段）
   challengeAttack?: number; // 挑战模式下的攻击（第一阶段）
   challengeDefense?: number; // 挑战模式下的防御
   challengeSpeed?: number;  // 挑战模式下的速度
   challengeSpirit?: number; // 挑战模式下的精神
   challengeSkillName?: string; // 挑战模式魂技名称（第一阶段）
  challengeSkillDesc?: string; // 挑战模式魂技描述（第一阶段）
  phase2ChallengeHp?: number;     // 第二阶段血量（情侣后全力形态）
  phase2ChallengeAttack?: number; // 第二阶段攻击
  phase2ChallengeSkillName?: string; // 第二阶段魂技名称
  phase2ChallengeSkillDesc?: string; // 第二阶段魂技描述
   spouseArtifactId?: string; // 结为夫妻后获得的专属神器ID
   /** 是否为一次性挑战角色（击败后永久消失，不可再次相遇） */
   isOneTimeVictory?: boolean;
    /** 击败后获得的特殊物品ID（落入背包，被动生效） */
    victoryArtifactItemId?: string;
    /** 是否为特殊存在（无好感度系统、只有切磋+遗忘，单独分类显示） */
    isSpecialBeing?: boolean;
    /** 是否无冷却（可无限次挑战） */
    noCooldown?: boolean;
    /** 击败奖励：永久称号 */
    victoryRewardTitle?: string;
    /** 属性（元素/武魂属性） */
    element?: string;
  }

/** 茶城6个节点 */
export interface TeaCityNode {
  id: string;
  name: string;
  description: string;
  icon: string;
  characterIds: string[]; // 可能遇到的人物id列表
}

